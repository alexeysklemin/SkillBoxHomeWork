//Задание 1. Кукушка
//Напишите программу, которая имитировала бы часы с кукушкой.
// В начале работы она спрашивает, который час, а затем нужное количество раз пишет «Ку - ку!».
// При выполнении задания необходимо обеспечить контроль ввода(например, количество часов не может быть отрицательным).
//Обратите внимание, если вы захотите использовать 24 - часовой формат, в котором часы имеют значения 0–23, то кукушка не сможет вас оповестить о полночи(нулевой час).
//Что оценивается
//• Есть проверка входных значений.
//• Количество выведенных на консоль фраз равно количеству часов.
//Solved

#include <iostream>
#include <chrono>
#include <ctime>

int main()
{
    // Получаем текущее время
    auto currentTime = std::chrono::system_clock::now();

    // Преобразуем в time_t
    std::time_t currentTimeT = std::chrono::system_clock::to_time_t(currentTime);

    // Преобразуем time_t в структуру tm
    std::tm localTime;
    localtime_s(&localTime, &currentTimeT); // Используем безопасную версию

    // Получаем часы
    int hours = localTime.tm_hour;

    for (int i = 0; i < hours; ++i)
    {
        std::cout << "KY-KY\n";
    }
}

