#include <iostream>

int fibonacci(int N)
{
    if (N == 0)// Базовый случай: fibonacci(0) = 0 прописывать обязательно!
    {
        return 0;
    }
    else
    {
        if (N == 1)// Базовый случай: fibonacci(1) = 1 прописывать обязательно!
        {
            return 1;
        }
    }
    
    
       return fibonacci(N-1)+fibonacci(N-2);

    
    
}


int main()
{
    int N = 0;
    std::cout << "Input N element of Fibonachi \t";
    std::cin >> N;
    if (N < 2147483647)
    {
        int result = fibonacci(N);
        std::cout << "\n" << result;
    }
}

