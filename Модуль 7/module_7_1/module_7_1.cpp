// Чтобы прикинуть гречневый бюджет, вы решили написать программу, которая выведет информацию о том, сколько килограммов гречки у вас должно быть в запасе 
// через месяц, два и так далее, пока она не закончится.
//Solved

#include <iostream>

int main()
{
    int grecha = 100;
    int monthResource = 4;
    int i = 1;

    while (grecha>=monthResource)
    {
        if (grecha < monthResource)
        {
            break;
        }
        grecha = grecha - monthResource;

        std::cout << "In " << i << " month we have " << grecha << " kg grecha"<<std::endl;
        i++;
    }
}

