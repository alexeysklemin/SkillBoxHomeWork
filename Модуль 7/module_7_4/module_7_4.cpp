// module_7_4.cpp : Напишите программу, которая рисует с помощью символьной графики прямоугольную рамку. 
// Для вертикальных линий используйте символ вертикального штриха «|», а для горизонтальных — дефис «-». Пусть пользователь вводит ширину и высоту рамки.
//Решена

#include <iostream>

int main()
{
    int height = 6;
    int width = 4;

    int i, j;

    std::cin >> height >> width;

    i = 0;
    while (i <= height)
    {
        std::cout << "|";
        j = 0;
        while (j <= width)
        {
            if ((i == 0) or (i == height))
            {
                std::cout << "-";
            }
            else
            {
                std::cout << " ";
            }
            j++;
        }
        std::cout << "|\n";
        i++;
    }
}

