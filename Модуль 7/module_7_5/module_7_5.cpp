// module_7_5.cpp : Модифицируйте пример с координатными осями так, чтобы в точке их пересечения рисовался знак «+», на верхнем конце вертикальной оси была стрелка вверх «^», 
// а на правом конце горизонтальной оси — стрелка вправо «>». Это сделает рисунок более красивым и точным.
//Solved

#include <iostream>

int main() {
    int height = 10;
    int width = 10;

    std::cin >> height >> width;
    // Центр координатной плоскости (индексы начинаются с 0)
    int center_x = width / 2;     // Вертикальная ось (Y)
    int center_y = height / 2;     // Горизонтальная ось (X)

    for (int j = 0; j < height; j++) {
        for (int i = 0; i < width; i++) {
            // 1. Стрелка оси Y (вверху)
            if (j == 0 && i == center_x) {
                std::cout << '^';
            }
            // 2. Стрелка оси X (справа)
            else if (j == center_y && i == width - 1) {
                std::cout << '>';
            }
            // 3. Центр координат (пересечение осей)
            else if (i == center_x && j == center_y) {
                std::cout << '+';
            }
            // 4. Вертикальная ось Y
            else if (i == center_x) {
                std::cout << '|';
            }
            // 5. Горизонтальная ось X
            else if (j == center_y) {
                std::cout << '-';
            }
            // 6. Пустое пространство
            else {
                std::cout << ' ';
            }
        }
        std::cout << '\n';  // Перевод строки после каждой строки
    }
}