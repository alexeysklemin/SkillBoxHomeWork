/*Есть код программы с двумя переменными типа int и выводом этих переменных на экран. 
Напишите программу, которая меняет значения переменных местами, 
то есть нужно добиться того, чтобы в переменной a лежит значение b, а в b — значение a.*/
//Решено
#include <iostream>

int main(){
    int a = 42;
    int b = 153;
    int tmp = 0;
    std::cout << a << " " << b << std::endl;
    tmp = a;
    a = b;
    b = tmp;
    std::cout << a << " " << b << std::endl;
}

