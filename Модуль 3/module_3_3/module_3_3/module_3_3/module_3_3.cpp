/*На бамбуковой плантации завелись гусеницы. Они спят днём и едят бамбук ночью. Бамбук генно-модифицированный, растёт только при свете дня, 
зато очень быстро — по 50 сантиметров ежедневно! Гусеницы съедают 20 сантиметров бамбука каждую ночь. Бамбуковые саженцы при посадке утром 
имеют высоту один метр. 
Напишите программу, которая считает, какой высоты будет бамбук в середине третьего дня. 
Усложнение — посчитайте это не за несколько подходов, а одной формулой.
*/
//Решено

#include <iostream>

int main() {
	int bambooLength = 100;
	int bambooGroth = 50;
	int caterpillarsMeael = 20;

	bambooLength = bambooLength + 3*(bambooGroth - caterpillarsMeael)-bambooGroth/2;

	std::cout << bambooLength;

}