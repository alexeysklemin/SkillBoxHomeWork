// =================================================================
// МЕТОД: Получить меню на СЕГОДНЯ
// Возвращает: указатель на массив из 4 блюд (const std::string*)
// Примечание: День недели определяется автоматически из системы
// =================================================================
const std::string* everydayDishes::getMenu() const
{
    // =============================================================
    // ШАГ 1: Получаем текущее время от системы
    // =============================================================
    std::time_t now = std::time(nullptr);

    // std::localtime() преобразует "сырое" время (seconds since epoch)
    // в структуру std::tm, которая содержит расчленённые данные:
    // год, месяц, день, час, минуту, секунду, день недели и т.д.
    //
    // ⚠️ Важно: Функция возвращает указатель на статический внутренний буфер.
    // Не сохраняй этот указатель надолго — он может быть перезаписан
    // следующим вызовом localtime() в другом месте программы.
    // Для наших целей (сразу прочитать tm_wday) — это безопасно.
    std::tm* localTime = std::localtime(&now);


    // =============================================================
    // ШАГ 2: Конвертируем системный день недели в наш enum
    // =============================================================
    int cDayIndex = localTime->tm_wday;

    // Конвертация: приводим стандарт C к нашему enum weekDay.
    //
    // Логика:
    // • Если cDayIndex == 0 (Воскресенье по стандарту C)
    //   → нам нужно 6 (Sunday по нашему enum).
    // • Иначе (Понедельник-Суббота, 1-6 по стандарту)
    //   → нам нужно 0-5 (просто вычитаем 1).
    //
    // Примеры:
    // • C: 1 (Пн) → (1-1) = 0 → наш enum: Monday
    // • C: 6 (Сб) → (6-1) = 5 → наш enum: Saturday
    // • C: 0 (Вс) → условие (0==0) → 6 → наш enum: Sunday
    weekDay myIndex = static_cast<weekDay>((cDayIndex == 0) ? 6 : (cDayIndex - 1));


    // =============================================================
    // ШАГ 3: Возвращаем меню для полученного дня
    // =============================================================

    // static_cast<weekDay>(myIndex) — явно преобразуем int в enum.
    // Это безопасно, потому что мы сами контролируем диапазон (0-6).
    //
    // dishes[...] — обращаемся к двумерному массиву:
    // • Первая координата: день недели (0-6)
    // • Вторая координата: номер блюда (0-3), выбирается позже
    //
    // Возвращаем указатель на первый элемент строки массива.
    // Вызывающая сторона получит доступ ко всем 4 блюдам:
    // menu[0] = первое блюдо, menu[1] = второе, и т.д.
    //
    // ⚠️ Важно: Возвращаем const std::string*, чтобы нельзя было
    // изменить исходные данные меню извне (защита от случайных правок).
    return dishes[static_cast<weekDay>(myIndex)];
}
