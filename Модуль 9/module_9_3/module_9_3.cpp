//Пользователь вводит строку, состоящую из произвольных символов и пробелов.Программа должна вывести одно число — количество слов во введённой строке.
//Solved

#include <iostream>
#include <string>

int wordCounting(std::string line){
    int count = 0;
    for (int i = 0; i < line.length(); ++i) {
        if (line[i] == ' ' && line[i+1] != ' '){
            count++;
        }
    }
    return count;
}

int main(){

    std::string line = {};
    std::cout << "Input your string ";
    std::cin >> line;
    std::cout << wordCounting(line);
}

